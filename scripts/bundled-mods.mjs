import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

/** The modpack every flight starts with. Its dependencies decide what this app bundles. */
export const DEFAULT_MODPACK = "0SFS/default-modpack";

/** The generated module, relative to the app's folder. */
export const BUNDLED_MODS_FILE = "src/flight/mods/bundledMods.ts";

/**
 * The default modpack and every mod it brings in, each mod after the mods it
 * depends on and the pack last.
 *
 * Each `0SFS/<Repo>` is the linked `@0sfs/*` dependency in package.json whose
 * folder is named <Repo>, so the flight serves its files and bundles its manifest.
 * A mod the pack needs that is not linked is an error: the build would ship
 * without it.
 *
 * @param {string} root the app's folder
 * @returns {{ source: string, packageName: string, name: string }[]}
 */
export function bundledMods(root) {
  const app = JSON.parse(readFileSync(path.join(root, "package.json"), "utf8"));
  /** @type {Map<string, { packageName: string, folder: string }>} */
  const linked = new Map();
  for (const [packageName, version] of Object.entries(app.dependencies ?? {})) {
    if (!packageName.startsWith("@0sfs/") || !version.startsWith("file:")) continue;
    const folder = path.resolve(root, version.slice(5));
    linked.set(path.basename(folder).toLowerCase(), { packageName, folder });
  }

  /** @type {{ source: string, packageName: string, name: string }[]} */
  const order = [];
  const done = new Set();
  /** @param {string} source @param {string[]} stack */
  const visit = (source, stack) => {
    const match = /^([^/]+)\/([^/@]+)(?:@HEAD)?$/.exec(source.trim());
    if (!match || match[1].toLowerCase() !== "0sfs") {
      throw new Error(`${stack.at(-1) ?? "The app"} needs ${source}. The default modpack bundles 0SFS/<Repo> mods only.`);
    }
    const key = match[2].toLowerCase();
    if (done.has(key)) return;
    if (stack.includes(key)) throw new Error(`Circular mod dependency: ${[...stack, key].join(" -> ")}`);
    const mod = linked.get(key);
    if (!mod) {
      throw new Error(`${stack.at(-1) ?? "The app"} needs ${source}, which package.json does not link. Add it as a file: dependency.`);
    }
    const manifestFile = path.join(mod.folder, "public", "0sfs-mod.json");
    if (!existsSync(manifestFile)) throw new Error(`${mod.packageName} has no public/0sfs-mod.json.`);
    const exported = JSON.parse(readFileSync(path.join(mod.folder, "package.json"), "utf8")).exports?.["./manifest"];
    if (exported !== "./public/0sfs-mod.json") throw new Error(`${mod.packageName} must export "./manifest" as "./public/0sfs-mod.json".`);
    const manifest = JSON.parse(readFileSync(manifestFile, "utf8"));
    for (const dependency of manifest.dependencies ?? []) {
      visit(typeof dependency === "string" ? dependency : dependency.source, [...stack, key]);
    }
    done.add(key);
    order.push({ source: `0SFS/${path.basename(mod.folder)}`, packageName: mod.packageName, name: identifier(path.basename(mod.folder)) });
  };
  visit(DEFAULT_MODPACK, []);
  return order;
}

/** `F-35B-external-tank` -> `f35bExternalTank`. @param {string} folder */
function identifier(folder) {
  const parts = folder.split(/[^A-Za-z0-9]+/).filter(Boolean);
  const name = parts.map((part, index) => index === 0 ? part.toLowerCase() : part[0].toUpperCase() + part.slice(1).toLowerCase()).join("");
  return /^[0-9]/.test(name) ? `mod${name}` : name;
}

/**
 * Writes src/flight/mods/bundledMods.ts from the default modpack, if it changed.
 * @param {string} root the app's folder
 * @returns {boolean} whether the file changed
 */
export function writeBundledMods(root) {
  const mods = bundledMods(root);
  const lines = [
    "// Generated by scripts/link-packs.mjs from @0sfs/default-modpack. Do not edit it:",
    "// change the modpack's dependencies, then run `node scripts/link-packs.mjs`.",
    'import type { OsfsModManifest } from "@0sfs/mods/schema";',
    ...mods.map(mod => `import ${mod.name} from "${mod.packageName}/manifest" with { type: "json" };`),
    "",
    "/** The modpack every flight starts with. */",
    `export const DEFAULT_MODPACK = ${JSON.stringify(DEFAULT_MODPACK)};`,
    "",
    "const manifests: readonly (readonly [string, unknown])[] = [",
    ...mods.map(mod => `  [${JSON.stringify(mod.source)}, ${mod.name}],`),
    "];",
    "",
    "/**",
    " * The default modpack and every mod it brings in, each mod after the mods it",
    " * depends on and the pack last. The manifests are bundled: installing them",
    " * fetches nothing.",
    " */",
    "export const BUNDLED_MODS = manifests as readonly (readonly [source: string, manifest: OsfsModManifest])[];",
    "",
  ];
  const file = path.join(root, BUNDLED_MODS_FILE);
  const next = lines.join("\n");
  if (existsSync(file) && readFileSync(file, "utf8") === next) return false;
  writeFileSync(file, next);
  return true;
}
