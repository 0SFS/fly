#!/usr/bin/env node
import { existsSync, lstatSync, mkdirSync, readdirSync, readFileSync, readlinkSync, rmdirSync, symlinkSync, unlinkSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Links the files the aircraft and engine packages serve into this app's public/.
 *
 * A package keeps the files it serves under its own public/, at the path the app
 * serves them from: C172's public/aircraft/cessna-172/Cessna_172_LOD0.glb is
 * /aircraft/cessna-172/Cessna_172_LOD0.glb. Each such file gets a link at the same
 * path in public/, so Vite serves it and copies it into the build like the app's
 * own files, and tests and scripts that read public/... from disk find it. The
 * packages are the linked `@0sfs/*` dependencies in package.json.
 *
 * Links that no longer match a package file are removed. A file of the app's own is
 * never replaced: two owners for one path is an error. The links are gitignored.
 *
 * Runs after `npm install` and whenever Vite loads its config (dev, build, tests):
 *
 *   node scripts/link-packs.mjs
 *
 * @param {string} [root] the app's folder
 * @returns {{ linked: number, created: number, removed: number }}
 */
export function linkPackPublicFiles(root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")) {
  const manifest = JSON.parse(readFileSync(path.join(root, "package.json"), "utf8"));
  const publicDir = path.join(root, "public");

  /** @type {Map<string, string>} public-relative path -> the package file it links to */
  const wanted = new Map();
  for (const [name, version] of Object.entries(manifest.dependencies ?? {})) {
    if (!name.startsWith("@0sfs/") || !version.startsWith("file:")) continue;
    const served = path.join(path.resolve(root, version.slice(5)), "public");
    if (!existsSync(served)) continue;
    for (const file of files(served)) {
      let relative = path.relative(served, file);
      // Each mod publishes public/0sfs-mod.json at the repository root. In this app
      // those files would collide, so the built-in copy is served at /mods/<repo>/.
      if (relative === "0sfs-mod.json") {
        relative = path.join("mods", path.basename(path.resolve(root, version.slice(5))).toLowerCase(), "0sfs-mod.json");
      }
      const other = wanted.get(relative);
      if (other) throw new Error(`public/${relative} is served by two packages: ${other} and ${file}`);
      wanted.set(relative, file);
    }
  }

  let removed = 0;
  for (const link of links(publicDir)) {
    const relative = path.relative(publicDir, link);
    const target = wanted.get(relative);
    if (target && readlinkSync(link) === path.relative(path.dirname(link), target)) continue;
    unlinkSync(link);
    removed++;
  }

  let created = 0;
  for (const [relative, target] of wanted) {
    const link = path.join(publicDir, relative);
    const stat = lstat(link);
    if (stat?.isSymbolicLink()) continue;
    if (stat) throw new Error(`public/${relative} is the app's own file and also served by ${target}`);
    mkdirSync(path.dirname(link), { recursive: true });
    symlinkSync(path.relative(path.dirname(link), target), link);
    created++;
  }
  pruneEmptyFolders(publicDir);
  mergeModJsbsimManifest(root, manifest);
  const ignore = ["# Generated by scripts/link-packs.mjs. Package files linked into public/.", ...[...wanted.keys()].sort()];
  writeFileSync(path.join(publicDir, ".gitignore"), ignore.join("\n") + "\n");
  return { linked: wanted.size, created, removed };
}

/** @param {string} file */
function lstat(file) {
  try {
    return lstatSync(file);
  } catch {
    return null;
  }
}

/** Every regular file under `folder`. @param {string} folder @returns {string[]} */
function files(folder, found = /** @type {string[]} */ ([])) {
  for (const entry of readdirSync(folder, { withFileTypes: true })) {
    const full = path.join(folder, entry.name);
    if (entry.isDirectory()) files(full, found);
    else if (entry.isFile()) found.push(full);
  }
  return found;
}

/** Every symbolic link under `folder`. @param {string} folder @returns {string[]} */
function links(folder, found = /** @type {string[]} */ ([])) {
  if (!existsSync(folder)) return found;
  for (const entry of readdirSync(folder, { withFileTypes: true })) {
    const full = path.join(folder, entry.name);
    if (entry.isSymbolicLink()) found.push(full);
    else if (entry.isDirectory()) links(full, found);
  }
  return found;
}

/**
 * Unions `jsbsimFiles` from linked mod manifests into the app manifest.
 * An aircraft key receives its own files plus the files of the `@0sfs` mods it depends on.
 * Existing entries stay in their current order; only missing paths are appended.
 * @param {string} root
 * @param {{ dependencies?: Record<string, string> }} appManifest
 */
function mergeModJsbsimManifest(root, appManifest) {
  const manifestPath = path.join(root, "public/jsbsim-data/manifest.json");
  if (!existsSync(manifestPath)) return;
  /** @type {Map<string, { kind?: string, jsbsimFiles?: string[], dependencies?: (string|{source:string})[], aircraft?: { fdmProfiles?: Record<string, unknown> } }>} */
  const mods = new Map();
  for (const [name, version] of Object.entries(appManifest.dependencies ?? {})) {
    if (!name.startsWith("@0sfs/") || !version.startsWith("file:")) continue;
    const file = path.join(path.resolve(root, version.slice(5)), "public", "0sfs-mod.json");
    if (!existsSync(file)) continue;
    mods.set(path.basename(path.resolve(root, version.slice(5))).toLowerCase(), JSON.parse(readFileSync(file, "utf8")));
  }
  const before = readFileSync(manifestPath, "utf8");
  const data = JSON.parse(before);
  if (!data || typeof data !== "object" || !Array.isArray(data.files) || !data.aircraft || typeof data.aircraft !== "object") return;
  const append = (list, file) => {
    if (typeof file === "string" && file && !list.includes(file)) list.push(file);
  };
  for (const mod of mods.values()) {
    if (mod.kind !== "aircraft" || !mod.aircraft?.fdmProfiles) continue;
    const dependencyFiles = [];
    for (const dependency of mod.dependencies ?? []) {
      const source = typeof dependency === "string" ? dependency : dependency.source;
      const slug = source.split("/").pop()?.replace(/@.*$/, "").toLowerCase();
      const dependencyMod = slug ? mods.get(slug) : undefined;
      for (const file of dependencyMod?.jsbsimFiles ?? []) dependencyFiles.push(file);
    }
    for (const [aircraftId, profile] of Object.entries(mod.aircraft.fdmProfiles)) {
      const list = data.aircraft[aircraftId];
      if (!Array.isArray(list)) continue;
      const model = profile && typeof profile === "object" && "model" in profile ? String(profile.model) : "";
      const belongs = file => file.startsWith("engine/") || (model !== "" && file.startsWith(`aircraft/${model}/`));
      for (const file of mod.jsbsimFiles ?? []) if (belongs(file)) append(list, file);
      for (const file of dependencyFiles) if (belongs(file)) append(list, file);
    }
  }
  // The top-level list is the default package. It stays equal to the Cessna list.
  if (Array.isArray(data.aircraft["cessna-172"])) data.files = data.aircraft["cessna-172"];
  const next = JSON.stringify(data, null, 2) + "\n";
  if (next !== before) writeFileSync(manifestPath, next);
}

/** Removes folders left empty under `folder`, but not `folder` itself. @param {string} folder */
function pruneEmptyFolders(folder) {
  for (const entry of readdirSync(folder, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const full = path.join(folder, entry.name);
    pruneEmptyFolders(full);
    if (readdirSync(full).length === 0) rmdirSync(full);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { linked, created, removed } = linkPackPublicFiles();
  console.log(`public/: ${linked} package files linked (${created} new, ${removed} removed)`);
}
